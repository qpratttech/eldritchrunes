## Summoned Creatures

Summoning spells use the profiles below and the modifications in their own entries. These are ready-to-use totals, not attributes to which skills must be added. Apply circumstances, Suffering, and Broken normally. A named summoned entity uses exactly the profile its spell assigns; its evocative name grants no additional abilities.

| Profile | Wounds | Attack Tier | Endurance | Reflexes | Willpower | Other Checks | Major / Minor Movement |
| :---- | ----: | ----: | ----: | ----: | ----: | ----: | :---- |
| Scout Summon | 1 | No attacks | 5 | 8 | 6 | 6 | 20 / 10 feet |
| Lesser Summon | 2 | 8 | 7 | 8 | 7 | 7 | 20 / 10 feet |
| Battle Summon | 4 | 10 | 9 | 9 | 9 | 8 | 20 / 10 feet |
| Greater Summon | 5 | 11 | 11 | 10 | 10 | 9 | 20 / 10 feet |
| Mighty Summon | 7 | 12 | 12 | 10 | 11 | 10 | 30 / 15 feet |

&nbsp;

A Lesser Summon’s normal strike deals 1 wound; Battle, Greater, and Mighty strikes deal 2, unless an entry replaces that damage. The spell supplies the damage type, special movement, and other abilities. Melee reach is 5 feet unless changed by the spell. Natural strikes deal normal damage rather than Lesser Attack damage and do not suffer the armed-target penalty. A summon has no Armor Save unless its spell grants one. All have critical range 01–03 and no Luck, Stamina, independent spells, techniques, or automatic Responses.

For an uncommon saving skill not in the table, use Other Checks. A specifically listed skill, such as Survival or Awareness, uses the spell’s replacement tier where stated. Ordinary summons occupy one 5-foot space unless their spell specifies a larger body. Sight and hearing are ordinary; a dark origin does not automatically grant Nightvision.

**Turns and commands:** A summon acts immediately after its controller with one major action, two minor actions, and one free action. Spend a minor action on your turn to command one summon within 60 feet that can perceive you. That command permits its offensive actions for that turn, including one major-action attack. Additional attacks require explicit permission and normal minor actions and penalties; none of these base profiles grants such permission. Summoning does not include a free command. Multiple creatures sharing one Focus slot still require separate commands.

Without a combat command, a summon may move, withdraw, or Dodge but cannot attack or use an offensive ability. A **Scout Summon** given a noncombat errand can continue that specific errand for up to 1 minute without fresh commands, traveling within its spell’s stated limit. It may observe, carry its permitted load, and return, but cannot attack, manipulate intricate mechanisms, or independently change its instructions. This scout exception does not apply to offensive Lesser or stronger summons.

**Spirit traits:** A spirit summon does not breathe, eat, or sleep, is immune to ordinary Poisoned and Bleeding, and can affect creatures with its listed strike. It remains visible and substantial for targeting unless an entry says otherwise. It has no inherent flight, wall passage, Ethereal Save, or immunity to Physical damage.

**Undead traits:** An undead summon does not breathe, eat, or sleep and is immune to Bleeding, Poisoned, Fear, and Horror. Damage still causes Suffering as disruption to its animation. It cannot receive living-creature healing. It remembers nothing of its corpse’s former life and does not restore that person.

**Construct traits:** A construct summon does not breathe, eat, or sleep and is immune to Bleeding, Poisoned, Fear, and Horror. It still suffers damage and Suffering normally and does not receive ordinary living or undead healing.

**Defeat and duration:** At 0 Wounds a summon disappears or becomes ordinary remains as its spell directs, without a Death Save. All summons end when their Focus spell ends. An Unconscious controller therefore loses them immediately. Summons do not inherit the caster’s critical bonuses, weapon training, or damage bonuses unless explicitly granted. Empowered starting-Wound bonuses are added once, not on each command. Resistances work normally and do not provide complete damage immunity.

## Objects, Barriers, and Falling

A spell-created barrier uses its stated Wounds and Armor Save and is immune to Suffering and living-creature conditions. Destroying one section opens that section without automatic collapse damage. A physical barrier stops movement and supplies solid cover; an aura described as Fortified does neither. Objects cannot be harmed by spells restricted to living creatures or minds.

For ordinary unattended objects without existing statistics, the GM can use **1 Wound** for a fragile vial or trinket, **3 Wounds** for a wooden container or ordinary door, and **5 Wounds** for a sturdy reinforced object. Structural sections use **8 Wounds per 5-foot section** and a 20% Armor Save, adjusted when their substance warrants it. These are object defaults, not a promise that a spell can target every material. Damaging a lock can release it, while damaging a door need not destroy the surrounding wall.

Direct attacks against a stationary unattended object automatically hit when the attacker has legal reach or range and clear access. Without a roll they cannot critically hit. Objects have no Endurance or Suffering; use their Armor Save if any. A magical inscription on a worn or carried object cannot be targeted as an unattended object merely to bypass its bearer’s defenses. Ending an ongoing spell removes its magical effects, not an ordinary object, book, or purchased weapon.

A real stone, rune surface, bone, candle, empty vial, or token must exist when a spell requires one. Ordinary suitable objects have no minimum price unless specified. Consumed herbs, incense, and healer’s treatments are expended when casting begins. Conjured material cannot be used to generate profitable permanent equipment unless an entry explicitly leaves ordinary material, as water-creation spells do.

**Falling:** A fall of 10 feet or less normally deals no damage. For each full 10 feet beyond that, take 1 Physical damage, maximum 6, as one event bypassing Armor, Brace, and Ethereal. A Reflexes save reduces that total by 1 wound on success. A damaging fall also knocks the creature Prone. A spell that safely removes the first 30 feet applies the ordinary calculation only to the remaining distance. Ending levitation, flight, or a bridge uses its entry’s safe-descent rule before this calculation.

**Movement and load:** Normal major movement is 20 feet and minor movement 10 feet before modifiers. Carrying allowance is Strength step × 10 lb, with a maximum traveling load of twice that amount. Above the allowance, movement decreases by 5 feet and Athletics, Reflexes, and Stealth are Diminished. A rune’s extra carrying allowance modifies that allowance, not Strength, damage, or attack accuracy. Flying, swimming, or conjured passage does not remove load penalties.

## Condition Reference

Conditions apply immediately. Make each permitted save at the start of the affected creature’s turn unless a spell replaces that schedule. Periodic damage occurs after a failed condition save, not upon initial infliction unless the spell says so. A sustained spell’s end also ends conditions it sustains. Identical conditions do not stack; use only the stronger of Fear/Horror, Dazed/Staggered, and Vulnerable/Greater Vulnerable. Reducing a stronger condition does not grant another save against its lesser form on the same turn.

| Condition | Effect and Ordinary Ending Save |
| :---- | :---- |
| Bleeding | Endurance save or take 1 Physical damage. This condition’s periodic damage does not cause Suffering. |
| Blinded | Vision-dependent checks and attacks have Greater Diminishment. Faith save ends temporary supernatural blindness. Permanent Blinded requires explicitly restorative magic. |
| Burning | Endurance save or take 1 Fire damage, causing Suffering normally. A major action using water or smothering ends ordinary flames. |
| Chilled / Slowed | Reduce each movement allowance by 5 feet, minimum 0. Endurance save ends it unless sustained by equipment or an explicit source. Their movement penalties do not add together. |
| Confused | Willpower save. On failure, use available movement to approach the nearest ally safely and make one normal attack against it if possible. No reachable ally means no forced hostile action. |
| Controlled | Willpower save. On failure, the controller directs normal actions, without extra actions or compelled Luck expenditure. Direct self-harm orders grant another immediate Willpower save. |
| Dazed | One fewer minor action. Willpower save ends it. |
| Fear | Attacks and non-save checks are Diminished; cannot willingly approach its source. Willpower save ends it. |
| Fortified | Direct attacks against the creature are Diminished for the granting effect’s duration. |
| Frozen | Cannot move or take actions. Endurance save ends it. |
